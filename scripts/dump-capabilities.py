#!/usr/bin/env python3
"""Dump every adapter's capability support from the RESOLVED EdgeZero checkout.

The expected-support table in the plan and the spec is generated by this
script, never hand-edited: a hand-maintained table describes the
revision its author had in mind, while this one describes the revision
Cargo actually resolved.

It reads the checkout `Cargo.lock` points at, so it cannot drift from
the pin. Every variant of upstream's `Capability` enum is emitted —
including the ones auctioneer does not consume — because a capability
present upstream and absent from the table is a regeneration failure,
not an omission to tolerate.

Usage:
    scripts/dump-capabilities.py [--checkout DIR]

With no `--checkout`, the directory is derived from the `edgezero` git
source line in `Cargo.lock` and the local Cargo git-checkout cache.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ADAPTERS = ("axum", "cloudflare", "fastly", "spin")
EXPECTED_CAPABILITY_COUNT = 23


def resolved_revision(lockfile: pathlib.Path) -> str:
    """The single EdgeZero revision every `source =` line must carry."""
    revisions = set(
        re.findall(
            r'^source = "git\+[^"]*edgezero[^"]*#([0-9a-f]{40})"$',
            lockfile.read_text(),
            re.M,
        )
    )
    if len(revisions) != 1:
        sys.exit(f"expected exactly one edgezero revision, found {sorted(revisions)}")
    return revisions.pop()


def find_checkout(revision: str) -> pathlib.Path:
    """Cargo's git checkout for `revision`, by its short-hash directory."""
    roots = list(
        pathlib.Path.home().glob(
            f".asdf/installs/rust/*/git/checkouts/edgezero-*/{revision[:7]}"
        )
    ) + list(pathlib.Path.home().glob(f".cargo/git/checkouts/edgezero-*/{revision[:7]}"))
    if not roots:
        sys.exit(
            f"no local checkout for {revision}; run `cargo fetch` first, "
            "or pass --checkout"
        )
    return roots[0]


def capability_wire_names(checkout: pathlib.Path) -> list[tuple[str, str]]:
    """`(variant, wire-name)` in upstream's own declaration order."""
    manifest = (checkout / "crates/edgezero-core/src/manifest.rs").read_text()
    body = re.search(r"pub enum Capability \{(.*?)\n\}", manifest, re.S)
    if body is None:
        sys.exit("Capability enum not found in upstream manifest.rs")
    variants = [
        line.strip().rstrip(",")
        for line in body.group(1).strip().splitlines()
        if line.strip() and not line.strip().startswith("//")
    ]
    wire = dict(re.findall(r'Self::(\w+) => "([a-z0-9-]+)"', manifest))
    missing = [v for v in variants if v not in wire]
    if missing:
        sys.exit(f"variants with no wire name: {missing}")
    return [(v, wire[v]) for v in variants]


def adapter_support(checkout: pathlib.Path, adapter: str, variants: list[str]) -> dict[str, str]:
    """One adapter's `capability()` match, resolved for every variant."""
    source = (checkout / f"crates/edgezero-adapter-{adapter}/src/cli.rs").read_text()
    body = re.search(
        r"fn capability\(&self, capability: Capability\) -> CapabilitySupport \{"
        r"\n\s*match capability \{(.*?)\n        \}\n    \}",
        source,
        re.S,
    )
    if body is None:
        sys.exit(f"capability() match not found for the {adapter} adapter")

    support: dict[str, str] = {}
    fallthrough = "Unsupported"
    for patterns, kind in re.findall(
        r"((?:\s*(?:\||Capability::\w+|_)[^=]*?))=> CapabilitySupport::(\w+),", body.group(1)
    ):
        for variant in re.findall(r"Capability::(\w+)", patterns):
            support.setdefault(variant, kind)
        if re.search(r"(^|\|)\s*_\s*$", patterns.strip(), re.M) or "| _" in patterns:
            fallthrough = kind
    return {variant: support.get(variant, fallthrough) for variant in variants}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkout", type=pathlib.Path)
    args = parser.parse_args()

    lockfile = pathlib.Path(__file__).resolve().parent.parent / "Cargo.lock"
    revision = resolved_revision(lockfile)
    checkout = args.checkout or find_checkout(revision)

    capabilities = capability_wire_names(checkout)
    if len(capabilities) != EXPECTED_CAPABILITY_COUNT:
        sys.exit(
            f"upstream declares {len(capabilities)} capabilities, this dump "
            f"expects {EXPECTED_CAPABILITY_COUNT} — update the constant and "
            "regenerate every table"
        )

    variants = [variant for variant, _wire in capabilities]
    table = {a: adapter_support(checkout, a, variants) for a in ADAPTERS}

    print(f"<!-- generated by scripts/dump-capabilities.py from {revision} -->")
    print("| Capability | Axum | Cloudflare | Fastly | Spin |")
    print("|---|---|---|---|---|")
    for variant, name in sorted(capabilities, key=lambda pair: pair[1]):
        cells = " | ".join(table[adapter][variant] for adapter in ADAPTERS)
        print(f"| {name} | {cells} |")


if __name__ == "__main__":
    main()
